export const isFeatureAvailable = (featureKey: string, userPlan = "basic"): boolean => {
  // Extract category and feature from the key (e.g., "plagiarismChecker.deepScan")
  const [category, feature] = featureKey.split(".")

  if (!category || !feature || !premiumFeatures[category as keyof typeof premiumFeatures]) {
    return false
  }

  const featureObj = premiumFeatures[category as keyof typeof premiumFeatures][feature as any]

  if (!featureObj) {
    return false
  }

  // If feature is free, it's available to all plans
  if (featureObj.free) {
    return true
  }

  // Otherwise, check if the user's plan allows it
  switch (userPlan) {
    case "basic":
      return false
    case "standard":
      return ["deepScan", "aiDetection", "fullSourceAccess"].includes(feature)
    case "premium":
    case "enterprise":
      return true
    default:
      return false
  }
}

export const getUserPlan = (): string => {
  if (typeof window === "undefined") return "basic"

  try {
    const user = JSON.parse(localStorage.getItem("user") || "{}")
    return user.plan || "basic"
  } catch {
    return "basic"
  }
}
